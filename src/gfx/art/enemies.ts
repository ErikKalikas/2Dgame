import type { Sprite } from '../sprite';
import { Grid } from './pix';

// Рядовые враги, нарисованные вручную. Все смотрят вправо (рендер отражает их сам).
// Индексы палитры: 0 пустота, 1 чёрный, 2 тёмный металл, 3 металл, 4 сталь, 5 светлая сталь,
// 6 серый, 7 кость, 8 запёкшаяся кровь, 9 тёмно-красный, a красный, b алый, c тёмный янтарь,
// d янтарь, e жёлтый, f фиолетовый. Обводка 0 добавляется автоматически.

type Layer = [string[], number, number];

function frame(w: number, h: number, layers: Layer[]): Sprite {
  const g = new Grid(w, h);
  for (const [r, x, y] of layers) g.rows(r, x, y);
  return g.outline(0).toSprite();
}

/**
 * Ноги в три четверти (смотрят вправо): 0 — стоит, 1 и 2 — шаги.
 * T — светлая сторона, S — тень, B — ботинок.
 */
function legs(f: number, T = '3', S = '2', B = '4', long = false): string[] {
  const L = [
    ['.TS.TS..', '.TS.TS..', '.TS.TS..', '.BB.BBB.'],
    ['.TSTTS..', 'TS...TS.', 'TS...TS.', 'BB...BBB'],
    ['..TTS...', '..TSTS..', '..TS.BB.', '..BBB...'],
  ][f];
  const rows = long ? [L[0], ...L] : L;
  return rows.map((r) => r.replace(/T/g, T).replace(/S/g, S).replace(/B/g, B));
}

/** Гуманоид: верх + ноги на 3 кадра */
function walker(w: number, h: number, top: string[], lx: number, opts: { T?: string; S?: string; B?: string; long?: boolean; extra?: (f: number) => Layer[] } = {}): Sprite[] {
  return [0, 1, 2].map((f) =>
    frame(w, h, [[legs(f, opts.T, opts.S, opts.B, opts.long), lx, top.length], [top, 0, 0], ...(opts.extra?.(f) ?? [])]),
  );
}

